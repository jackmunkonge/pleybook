import { modelsUsed, type FindingView } from "@/lib/review/view";

export function ProviderBadge({ findings }: { findings: FindingView[] }) {
  const models = modelsUsed(findings);
  const skipped = findings.filter((f) => f.clauseId && !f.modelUsed).length;
  return (
    <p className="text-xs text-zinc-500">
      {models.length ? `Generated by ${models.join(", ")}` : "No model calls yet"}
      {skipped > 0 && ` · ${skipped} clause${skipped === 1 ? "" : "s"} matched no playbook rule (no LLM call)`}
    </p>
  );
}
